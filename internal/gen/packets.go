package main

import (
	"bytes"
	"cmp"
	"encoding/json"
	"fmt"
	"go/format"
	"maps"
	"os"
	"path/filepath"
	"slices"
)

type packetFileJson map[string]map[string]map[string]packet

func genPackets(dataDir, outDir string) error {
	data, err := os.ReadFile(dataDir)
	if err != nil {
		return err
	}
	var r packetFileJson
	if err := json.Unmarshal(data, &r); err != nil {
		return err
	}

	for _, packetTypeKey := range slices.Sorted(maps.Keys(r)) {
		packetTypeValue := r[packetTypeKey]
		for _, boundKey := range slices.Sorted(maps.Keys(packetTypeValue)) {
			boundValue := packetTypeValue[boundKey]
			dir := filepath.Join(outDir, packetTypeKey, boundKey)
			os.MkdirAll(dir, 0o755)
			var b bytes.Buffer
			b.WriteString(fmt.Sprintf("// Code generated by internal/gen/packets.go; DO NOT EDIT.\n\npackage %s\n\n", boundKey))

			names := slices.Collect(maps.Keys(boundValue))
			slices.SortFunc(names, func(a, b string) int {
				return cmp.Compare(boundValue[a].ProtocolID, boundValue[b].ProtocolID)
			})

			b.WriteString("const (\n")
			for _, packetName := range names {
				fmt.Fprintf(&b, "\t%s int32 = 0x%02X\n", goName(packetName), boundValue[packetName].ProtocolID)
			}
			b.WriteString(")\n")

			src, err := format.Source(b.Bytes())
			if err != nil {
				return fmt.Errorf("format %s/%s: %w\n%s", packetTypeKey, boundKey, err, b.String())
			}
			if err := os.WriteFile(filepath.Join(dir, "packet_id.go"), src, 0o644); err != nil {
				return err
			}
		}
	}

	return nil
}
