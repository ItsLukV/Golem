package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
)

type registry struct {
	Entries map[string]packet `json:"entries"`
}

type report map[string]registry

func genBlocks(dataDir, outDir string) error {
	data, err := os.ReadFile(dataDir)
	if err != nil {
		return err
	}
	var r report
	if err := json.Unmarshal(data, &r); err != nil {
		return err
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by blocks.go; DO NOT EDIT.\n\npackage blocks\n\n")
	entries := r["minecraft:block"].Entries
	names := make([]string, 0, len(entries))
	for name := range entries {
		names = append(names, name)
	}
	sort.Slice(names, func(i, j int) bool { return entries[names[i]].ProtocolID < entries[names[j]].ProtocolID })

	b.WriteString("const (\n")
	for _, name := range names {
		b.WriteString(fmt.Sprintf("\t%s int32 = %d\n", goName(name), entries[name].ProtocolID))
	}
	b.WriteString(")\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}

	os.MkdirAll(outDir, 0o755)
	if err := os.WriteFile(outDir+"/blocks.go", src, 0o644); err != nil {
		return err
	}
	return nil
}
