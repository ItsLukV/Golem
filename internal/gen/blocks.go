package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
)

type blockState struct {
	ID      int32 `json:"id"`
	Default bool  `json:"default"`
}

type block struct {
	States []blockState `json:"states"`
}

type blocksReport map[string]block

func (b block) defaultState() int32 {
	for _, s := range b.States {
		if s.Default {
			return s.ID
		}
	}
	return b.States[0].ID
}

func genBlocks(dataDir, outDir string) error {
	data, err := os.ReadFile(dataDir)
	if err != nil {
		return err
	}
	var r blocksReport
	if err := json.Unmarshal(data, &r); err != nil {
		return err
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by blocks.go; DO NOT EDIT.\n\npackage blocks\n\n")
	names := make([]string, 0, len(r))
	for name := range r {
		names = append(names, name)
	}
	sort.Slice(names, func(i, j int) bool { return r[names[i]].defaultState() < r[names[j]].defaultState() })

	b.WriteString("const (\n")
	for _, name := range names {
		b.WriteString(fmt.Sprintf("\t%s int32 = %d\n", goName(name), r[name].defaultState()))
	}
	b.WriteString(")\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}

	os.MkdirAll(outDir, 0o755)
	if err := os.WriteFile(outDir+"/blocks.go", src, 0o644); err != nil {
		return err
	}
	return nil
}
